export function loadBenchmarkDataset(filePath?: string): BenchmarkCase[] {
    if (!filePath) {
        return REPRESENTATIVE_BENCHMARK_DATASET;
    }
    if (!fs.existsSync(filePath)) {
        throw new Error(`Benchmark dataset file not found: ${filePath}`);
    }
    const raw = fs.readFileSync(filePath, 'utf-8');
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed)) {
        throw new Error(`Invalid benchmark dataset format: expected array of BenchmarkCase in ${filePath}`);
    }
    for (let i = 0; i < parsed.length; i++) {
        const item = parsed[i];
        if (!item.id || !item.prompt || !Array.isArray(item.expectedSkills)) {
            throw new Error(`Invalid benchmark case at index ${i}: missing id, prompt, or expectedSkills`);
        }
    }
    return parsed as BenchmarkCase[];
}

